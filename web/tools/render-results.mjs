// Rewrites the "Results" block of README.md from reports/*.json, so no number in the README is typed by hand.
//   npm run build && npm run check && npm run prove:scale && node tools/selftest.mjs && node tools/tools-add-client-run, then:
//   node tools/render-results.mjs
import fs from 'node:fs';
import path from 'node:path';
import { WEB_ROOT } from './lib.mjs';

const R = (f) => JSON.parse(fs.readFileSync(path.join(WEB_ROOT, 'reports', f), 'utf8'));
const build = R('build.json');
const quality = R('quality.json');
const proof = R('scale-proof.json');
const selftest = R('selftest.json');
const addClient = fs.existsSync(path.join(WEB_ROOT, 'reports', 'add-client.json')) ? R('add-client.json') : null;
if (proof.verdict !== 'PASS') throw new Error('scale-proof.json is not PASS: refusing to publish numbers');

const kb = (n) => (n / 1024).toFixed(1);
const sites = build.map((b) => b.site);
const cell = (fn) =>
  sites
    .map((s) =>
      fn(
        s,
        build.find((b) => b.site === s),
        quality.sites[s],
      ),
    )
    .join(' | ');
const t = proof.templateChange;

const block = `<!-- results:start (generated by tools/render-results.mjs from reports/*.json; do not edit by hand) -->
Run on ${quality.date.slice(0, 10)} (Windows, Node ${process.version}, Astro 7.4.4). Numbers vary a little from run to run.

| Metric | ${sites.join(' | ')} |
|---|${sites.map(() => '---').join('|')}|
| Pages (HTML) | ${cell((s, b) => b.htmlPages)} |
| Build, Astro page generation / wall clock incl. startup | ${cell((s, b) => `${b.astroSeconds} s / ${b.seconds} s`)} |
| HTML per page, avg raw / gzip / brotli | ${cell((s, b, q) => `${kb(q.weight.avgHtmlRaw)} / ${kb(q.weight.avgHtmlGzip)} / ${kb(q.weight.avgHtmlBrotli)} KB`)} |
| Largest page (gzip) | ${cell((s, b, q) => `${kb(q.weight.maxHtmlGzip)} KB`)} |
| Requests per page (avg), JavaScript files | ${cell((s, b, q) => `${q.weight.avgRequests}, 0`)} |
| JSON-LD blocks, all valid | ${cell((s, b, q) => q.jsonld.scripts)} |
| Internal links checked / broken / orphan pages | ${cell((s, b, q) => `${q.links.internalLinks} / ${q.links.failures.filter((f) => /broken/.test(f)).length} / ${q.links.failures.filter((f) => /orphan/.test(f)).length}`)} |
| axe-core WCAG 2.x A/AA: runs, violating nodes | ${cell((s, b, q) => `${q.browser.axeRuns}, ${q.browser.violations}`)} |
| Lab LCP worst / CLS worst (headless Chrome, no throttling) | ${cell((s, b, q) => `${q.browser.worstLcpMs} ms / ${q.browser.worstCls}`)} |

Scale proof (\`npm run prove:scale\`, verdict ${proof.verdict}): control rebuild changed ${proof.control.changedFiles} files; the footer change touched ${t.changedFiles} files across ${t.sites} sites, of which ${t.onlyFooterChanged} of ${t.htmlFiles} pages changed only inside \`<footer>\`, ${t.changedOutsideFooter} outside it, ${t.contentTextDiffs} content-text differences, ${t.nonHtmlChanged} sitemap/robots/llms.txt changes, +${t.footerBytesAddedTotal} bytes in total. Negative control: an edit outside the footer was flagged on ${proof.negativeControl.pagesFlaggedOutsideFooter} pages. After restoring the template: ${proof.restored.changedFiles} differences against the approved \`golden/\`.

Mutation probes (\`node tools/selftest.mjs\`): ${selftest.caught} of ${selftest.injected} injected defects caught; the pristine build passes: ${selftest.pristinePasses}.
${addClient ? `\nAdd-a-client run (${addClient.site}, ${addClient.pages} pages, ${addClient.posts} post, ${addClient.at.slice(0, 10)}): whole run (validate, scaffold, build, JSON-LD + links + weight gates) ${addClient.totalSeconds} s, gates passed: ${addClient.gatesPassed}. The site was deleted afterwards.\n` : ''}<!-- results:end -->`;

const readme = path.join(WEB_ROOT, 'README.md');
const text = fs.readFileSync(readme, 'utf8');
const re = /<!-- results:start[\s\S]*?<!-- results:end -->/;
if (!re.test(text)) throw new Error('results markers not found in README.md');
fs.writeFileSync(
  readme,
  text.replace(re, () => block),
);
console.log('README results block updated from reports/*.json');
